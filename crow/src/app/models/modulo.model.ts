/**
 * Ícone de reserva para módulos antigos salvos sem ícone. Deriva do id (nunca
 * aleatório), então o módulo mostra o mesmo ícone em todas as telas.
 */
export function iconeModuloPadrao(id: number): string {
  const total = ICONES_MODULO.length;
  const indice = ((((id || 1) - 1) % total) + total) % total;
  return ICONES_MODULO[indice].svg;
}
