import { SafeHtml } from '@angular/platform-browser';
import { Frase } from './frase.model';

export interface Modulo {
  id: number;
  nome: string;
  /** SVG sanitizado para renderização no template. */
  icone: SafeHtml;
  /** SVG bruto persistido no backend — usado como chave de seleção. */
  iconeSvg: string;
  selecionado: boolean;
  frases: number;
}

/** Módulo como o backend o entrega (ModuloResponse), sem sanitização do ícone. */
export interface ModuloAdm {
  id: number;
  codigo: string;
  nome: string;
  /** SVG bruto persistido; vazio quando o módulo usa o ícone padrão. */
  icone: string;
  ordem: number | null;
  frases: number;
  criadoEm?: string | null;
  atualizadoEm?: string | null;
}

/** Módulo acompanhado de todas as suas frases — visão de moderação, somente leitura. */
export interface ModuloCompletoAdm {
  modulo: ModuloAdm;
  frases: Frase[];
}

/** Ícone que o criador escolhe para um módulo. */
export interface IconeModulo {
  /** Tema representado — vira a dica (title) e o rótulo acessível da opção. */
  nome: string;
  /**
   * Miolo do `<svg viewBox="0 0 24 24">`. É o valor persistido em `icone` e a
   * chave que marca o ícone atual na edição: alterar o texto de um ícone já em
   * uso faz os módulos salvos com ele deixarem de aparecer como selecionados.
   */
  svg: string;
}

/**
 * Traço arredondado embutido no próprio ícone: o SVG salvo renderiza igual em
 * qualquer tela, inclusive os pontos (ex.: `h.01`), que somem com ponta reta.
 */
function icone(nome: string, miolo: string): IconeModulo {
  return { nome, svg: `<g stroke-linecap="round" stroke-linejoin="round">${miolo}</g>` };
}

